export function formatPrice(priceNgn: number, priceUsd: number, currency: Currency, listingType: string): string {
  const suffix = listingType === "for-rent" ? " / yr" : "";
  if (currency === "USD") {
    return `$${priceUsd.toLocaleString("en-US")}${suffix}`;
  }
  if (priceNgn >= 1_000_000_000) {
    return `₦${(priceNgn / 1_000_000_000).toFixed(2)}B${suffix}`;
  }
  if (priceNgn >= 1_000_000) {
    return `₦${(priceNgn / 1_000_000).toFixed(0)}M${suffix}`;
  }
  return `₦${priceNgn.toLocaleString("en-US")}${suffix}`;
}

export function formatFullPrice(value: number, currency: Currency): string {
  return currency === "USD"
    ? `$${value.toLocaleString("en-US")}`
    : `₦${value.toLocaleString("en-US")}`;
}

